#!/usr/bin/env python3
"""Summarize unified clustering benchmark results and export CSV/LaTeX tables."""
from __future__ import annotations

import argparse
import csv
import math
import statistics
from collections import defaultdict
from pathlib import Path

METRICS = ("ari", "nmi", "ami", "fit_seconds", "peak_rss_mb")


def number(value):
    try:
        result = float(value)
        return result if math.isfinite(result) else None
    except (TypeError, ValueError):
        return None


def latex_escape(value):
    return str(value).replace("_", r"\_").replace("%", r"\%")


def summarize(rows):
    groups = defaultdict(list)
    for row in rows:
        key = (row.get("dataset", ""), row.get("representation", ""),
               row.get("algorithm", ""))
        groups[key].append(row)

    summaries = []
    for (dataset, representation, algorithm), group in sorted(groups.items()):
        successful = [r for r in group if r.get("status", "").strip().lower() == "ok"]
        failed = len(group) - len(successful)
        nonconverged = sum(
            r.get("converged", "").strip().lower() == "false"
            for r in successful
        )
        item = {"dataset": dataset, "representation": representation,
                "algorithm": algorithm, "runs": len(group),
                "successful": len(successful), "failed": failed,
                "nonconverged": nonconverged}
        for metric in METRICS:
            values = [number(r.get(metric)) for r in successful]
            values = [v for v in values if v is not None]
            item[f"{metric}_n"] = len(values)
            item[f"{metric}_mean"] = statistics.mean(values) if values else None
            item[f"{metric}_sd"] = statistics.stdev(values) if len(values) >= 2 else None
        summaries.append(item)
    return summaries


def formatted(item, metric, digits=4):
    mean = item[f"{metric}_mean"]
    sd = item[f"{metric}_sd"]
    if mean is None:
        return "N/A"
    if sd is None:
        return f"{mean:.{digits}f} (SD N/A)"
    return f"{mean:.{digits}f} ± {sd:.{digits}f}"


def export_csv(items, path):
    fields = ["dataset", "representation", "algorithm", "runs", "successful",
              "failed", "nonconverged"]
    for metric in METRICS:
        fields.extend([f"{metric}_n", f"{metric}_mean", f"{metric}_sd"])
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(items)


def export_latex(items, path):
    lines = [
        r"% Generated by summarize_benchmark.py; SD is sample standard deviation.",
        r"% Nonconverged fits are included if their status is ok; inspect the warnings.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Clustering benchmark results across independent seeds (mean $\pm$ sample SD).}",
        r"\label{tab:benchmark-summary}",
        r"\small",
        r"\begin{tabular}{lllrrrrr}",
        r"\toprule",
        r"Dataset & Representation & Algorithm & Success & ARI & NMI & AMI & Fit (s) \\",
        r"\midrule",
    ]
    for item in items:
        success = f"{item['successful']}/{item['runs']}"
        cells = [latex_escape(item[k]) for k in ("dataset", "representation", "algorithm")]
        cells += [success] + [formatted(item, metric, 3).replace("±", r"$\pm$")
                              for metric in ("ari", "nmi", "ami", "fit_seconds")]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default="outputs/benchmark/dtd_multiseed.csv")
    parser.add_argument("--output-csv", default="outputs/benchmark/dtd_summary.csv")
    parser.add_argument("--output-tex", default="outputs/benchmark/dtd_summary.tex")
    args = parser.parse_args()
    source = Path(args.input)
    if not source.is_file():
        parser.error(f"Input CSV not found: {source}")
    with source.open(newline="") as handle:
        reader = csv.DictReader(handle)
        required = {"dataset", "representation", "algorithm", "status", *METRICS}
        missing = required - set(reader.fieldnames or [])
        if missing:
            parser.error(f"Missing required CSV columns: {', '.join(sorted(missing))}")
        rows = list(reader)
    if not rows:
        parser.error("Input CSV contains no data rows")

    items = summarize(rows)
    print(f"Benchmark summary: {source}")
    print(f"{'Representation':<16} {'Algorithm':<10} {'OK':>5} {'ARI':>23} {'NMI':>23} {'AMI':>23} {'Time (s)':>23} {'RSS (MB)':>23}")
    for item in items:
        print(f"{item['representation']:<16} {item['algorithm']:<10} "
              f"{item['successful']}/{item['runs']: <3} "
              + " ".join(f"{formatted(item, metric, 4):>23}" for metric in METRICS))
        if item["failed"] or item["nonconverged"]:
            print(f"  WARNING: {item['failed']} failed; {item['nonconverged']} nonconverged successful fits")
    export_csv(items, Path(args.output_csv))
    export_latex(items, Path(args.output_tex))
    print(f"\nSummary CSV: {args.output_csv}")
    print(f"LaTeX table: {args.output_tex}")
    print("Note: peak RSS includes Python startup, imports, loading, and preprocessing.")


if __name__ == "__main__":
    main()

